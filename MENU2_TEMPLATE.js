const sections = MENU_TEMPLATE.split("\n\n");

export function getMenuChunks(maxChars = 3500) {
    const chunks = [];
    let current = "";
    for (const section of sections) {
        const next = current ? `${current}\n\n${section}` : section;
        if (current && next.length > maxChars) {
            chunks.push(current);
            current = section;
        } else {
            current = next;
        }
    }
    if (current) chunks.push(current);
    return chunks;
}

export async function sendMenuTemplate(sock, jid, quoted) {
    for (const text of getMenuChunks()) {
        await sock.sendMessage(jid, { text }, quoted ? { quoted } : undefined);
    }
}

